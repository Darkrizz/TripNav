"""Generates TripNav's logo as Android vector drawables (plus an optional PNG preview).

The mark is deliberately minimal: a wheel (a bold tyre ring and a hairline rim) with the navigation arrow
cutting up through it. Two flat colours on matte black; the arrow knocks out a thin gap where it crosses.
Everything is drawn on the 108x108 adaptive-icon canvas inside the 66 dp safe circle, so the same geometry
serves the launcher icon, the system splash and the in-app loading screen.

    python tools/make_logo.py                 # writes app/src/main/res/drawable/*.xml
    python tools/make_logo.py preview.png     # also renders a 512 px preview (needs Pillow)
"""
import os
import sys

WHEEL_C = (54.0, 57.0)      # wheel centre (slightly low, so wheel + arrow tip sit centred together)
TYRE_R, TYRE_W = 21.5, 4.6
RIM_R, RIM_W = 15.0, 1.4
KNOCK = 2.8                 # gap cut around the arrow where it crosses the wheel
ARROW = dict(tip=(54, 22.0), left=(43.0, 62.5), right=(65.0, 62.5), notch=(54, 55.0))

BG = "#FF0D0E11"
WHEEL = "#FFF2ECE1"         # warm off-white
EMBER_L, EMBER_R = "#FFFF6A1F", "#FFD9480F"   # two flat facets give the arrow a crisp fold

RES = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res")
NL = "\n"


def circle_path(r):
    cx, cy = WHEEL_C
    return "M%.2f,%.2f A%.2f,%.2f 0 1,1 %.2f,%.2f A%.2f,%.2f 0 1,1 %.2f,%.2f" % (
        cx, cy - r, r, r, cx, cy + r, r, r, cx, cy - r)


def poly(*pts):
    return "M" + " L".join("%.2f,%.2f" % q for q in pts) + " Z"


def arrow_halves():
    a = ARROW
    return (a["tip"], a["left"], a["notch"]), (a["tip"], a["notch"], a["right"])


def vector(body, size=108, viewport=108):
    return ('<?xml version="1.0" encoding="utf-8"?>' + NL + '<!-- Generated by tools/make_logo.py; edit that instead. -->' + NL
            + '<vector xmlns:android="http://schemas.android.com/apk/res/android"' + NL
            + '    android:width="%ddp" android:height="%ddp" android:viewportWidth="%d" android:viewportHeight="%d">'
            % (size, size, viewport, viewport) + NL + body + '</vector>' + NL)


def fill(path_data, color):
    return '    <path android:pathData="%s" android:fillColor="%s"/>%s' % (path_data, color, NL)


def stroke(path_data, color, width):
    return ('    <path android:pathData="%s" android:strokeColor="%s" android:strokeWidth="%.2f"'
            ' android:strokeLineJoin="round" android:fillColor="#00000000"/>%s') % (path_data, color, width, NL)


def wheel_xml(color):
    return stroke(circle_path(TYRE_R), color, TYRE_W) + stroke(circle_path(RIM_R), color, RIM_W)


def arrow_xml(left_color, right_color, knockout=None):
    left, right = arrow_halves()
    a = ARROW
    cut = stroke(poly(a["tip"], a["left"], a["notch"], a["right"]), knockout, KNOCK * 2) if knockout else ""
    return cut + fill(poly(*left), left_color) + fill(poly(*right), right_color)


def write(name, text):
    with open(os.path.join(RES, "drawable", name), "w", newline=NL) as f:
        f.write(text)


def main():
    write("ic_launcher_background.xml", vector(fill("M0,0h108v108h-108z", BG)))
    write("ic_launcher_foreground.xml", vector(wheel_xml(WHEEL) + arrow_xml(EMBER_L, EMBER_R, knockout=BG)))
    write("logo_tyre.xml", vector(wheel_xml(WHEEL)))
    write("logo_arrow.xml", vector(arrow_xml(EMBER_L, EMBER_R, knockout=BG)))
    # Monochrome (themed icons) and status bar: no knockout colour is available, so the arrow simply overlaps.
    mono = wheel_xml("#FFFFFFFF") + arrow_xml("#FFFFFFFF", "#FFFFFFFF")
    write("ic_launcher_monochrome.xml", vector(mono))
    write("ic_stat_ride.xml", vector('    <group android:translateX="-22" android:translateY="-20">' + NL + mono + '    </group>' + NL,
                                     size=24, viewport=64))
    if len(sys.argv) > 1:
        preview(sys.argv[1])


def preview(out, px=512):
    """Raster of the launcher icon (circle-masked) for eyeballing changes."""
    from PIL import Image, ImageDraw

    n = px * 4
    k = n / 108.0

    def rgba(h):
        return tuple(int(h[i:i + 2], 16) for i in (3, 5, 7)) + (int(h[1:3], 16),)

    img = Image.new("RGBA", (n, n), rgba(BG))
    d = ImageDraw.Draw(img)
    cx, cy = WHEEL_C
    for r, wd in ((TYRE_R, TYRE_W), (RIM_R, RIM_W)):
        w = wd * k
        d.ellipse([(cx - r) * k - w / 2, (cy - r) * k - w / 2, (cx + r) * k + w / 2, (cy + r) * k + w / 2],
                  outline=rgba(WHEEL), width=int(w))
    a = ARROW
    outline = [(x * k, y * k) for x, y in (a["tip"], a["left"], a["notch"], a["right"])]
    d.line(outline + [outline[0], outline[1]], fill=rgba(BG), width=int(KNOCK * 2 * k), joint="curve")
    left, right = arrow_halves()
    d.polygon([(x * k, y * k) for x, y in left], fill=rgba(EMBER_L))
    d.polygon([(x * k, y * k) for x, y in right], fill=rgba(EMBER_R))
    mask = Image.new("L", (n, n), 0)
    ImageDraw.Draw(mask).ellipse([18 * k, 18 * k, 90 * k, 90 * k], fill=255)
    final = Image.new("RGBA", (n, n), (255, 255, 255, 255))
    final.paste(img, (0, 0), mask)
    final.resize((px, px), Image.LANCZOS).save(out)


if __name__ == "__main__":
    main()
