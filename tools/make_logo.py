"""Generates TripNav's logo as Android vector drawables (plus an optional PNG preview).

The mark is a brass motorcycle tyre (slanted tread blocks, polished rim line) wrapped around an ember
navigation arrow. Everything is drawn on the 108x108 adaptive-icon canvas, inside the 66 dp safe circle,
so the same geometry serves the launcher icon, the system splash and the in-app loading screen.

    python tools/make_logo.py                 # writes app/src/main/res/drawable/*.xml
    python tools/make_logo.py preview.png     # also renders a 512 px preview (needs Pillow)
"""
import math
import os
import sys

C = 54.0
TYRE_OUT, TYRE_IN, GROOVE = 32.2, 22.4, 28.0   # tread block tips, bead (meets the rim), groove floor
BLOCKS, SLANT = 22, 7.0                         # tread blocks around the tyre, slant in degrees
RIM_R, RIM_W = 20.6, 3.6                        # polished brass rim
BEZEL_R, BEZEL_W = 34.4, 0.9                    # hairline brass bezel around the whole badge
ARROW = dict(tip=(54, 35.0), left=(42.0, 68.4), right=(66.0, 68.4), notch=(54, 60.6))

BG_IN, BG_OUT = "#FF2B1D12", "#FF060708"
BRASS = ["#FFF9E3A0", "#FFD9A84A", "#FF8F6020", "#FFE8BE62"]
RUBBER = ["#FF4A4F59", "#FF1A1C20", "#FF0E0F12"]
EMBER_L = ["#FFFFB868", "#FFFF6A1F"]
EMBER_R = ["#FFE8571A", "#FF9E3208"]

RES = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res")


def polar(r, deg):
    a = math.radians(deg - 90)
    return C + r * math.cos(a), C + r * math.sin(a)


def tyre_outline():
    """Outer silhouette: tread blocks with slanted flanks, separated by grooves."""
    pts = []
    step = 360.0 / BLOCKS
    for i in range(BLOCKS):
        a = i * step
        pts += [polar(GROOVE, a), polar(TYRE_OUT, a + SLANT), polar(TYRE_OUT, a + step * 0.62 + SLANT),
                polar(GROOVE, a + step * 0.62)]
    return pts


def circle(r, n=96):
    return [polar(r, i * 360.0 / n) for i in range(n)]


def fmt(p):
    return "%.2f,%.2f" % p


def path(*loops):
    return " ".join("M" + " L".join(fmt(p) for p in loop) + " Z" for loop in loops)


def ring_path(r, w):
    return path(circle(r + w / 2), list(reversed(circle(r - w / 2))))


def arrow_halves():
    a = ARROW
    return [a["tip"], a["left"], a["notch"]], [a["tip"], a["notch"], a["right"]]


def linear(x1, y1, x2, y2, colors):
    stops = "".join('<item android:offset="%.3f" android:color="%s"/>' % (i / (len(colors) - 1), c)
                    for i, c in enumerate(colors))
    return ('<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="%g" android:startY="%g" '
            'android:endX="%g" android:endY="%g">%s</gradient></aapt:attr>') % (x1, y1, x2, y2, stops)


def vector(body, size=108, viewport=108):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_logo.py; edit that instead. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="%ddp" android:height="%ddp" android:viewportWidth="%d" android:viewportHeight="%d">\n%s</vector>\n'
            % (size, size, viewport, viewport, body))


def p(data, fill, even_odd=False):
    rule = ' android:fillType="evenOdd"' if even_odd else ""
    if fill.startswith("<"):
        return '    <path android:pathData="%s"%s>%s</path>\n' % (data, rule, fill)
    return '    <path android:pathData="%s" android:fillColor="%s"%s/>\n' % (data, fill, rule)


def tyre_body():
    tyre = path(tyre_outline(), list(reversed(circle(TYRE_IN))))
    return (p(ring_path(BEZEL_R, BEZEL_W), linear(20, 20, 88, 88, BRASS))
            + p(tyre, linear(30, 22, 78, 86, RUBBER), even_odd=True)
            # Sidewall highlight: a faint lighter band halfway up the rubber.
            + p(ring_path((TYRE_IN + GROOVE) / 2, 1.0), "#33FFFFFF")
            + p(ring_path(RIM_R, RIM_W), linear(34, 32, 74, 76, BRASS))
            + p(ring_path(RIM_R - RIM_W / 2 + 0.35, 0.7), "#66000000"))


def arrow_body():
    left, right = arrow_halves()
    return (p(path(left), linear(54, 36, 46, 69, EMBER_L))
            + p(path(right), linear(54, 36, 62, 69, EMBER_R)))


def write(name, text):
    out = os.path.join(RES, "drawable", name)
    with open(out, "w", newline="\n") as f:
        f.write(text)


def main():
    bg = ('    <path android:pathData="M0,0h108v108h-108z"><aapt:attr name="android:fillColor">'
          '<gradient android:type="radial" android:centerX="54" android:centerY="42" android:gradientRadius="78">'
          '<item android:offset="0" android:color="%s"/><item android:offset="1" android:color="%s"/>'
          '</gradient></aapt:attr></path>\n') % (BG_IN, BG_OUT)
    write("ic_launcher_background.xml", vector(bg))
    write("ic_launcher_foreground.xml", vector(tyre_body() + arrow_body()))
    write("logo_tyre.xml", vector(tyre_body()))
    write("logo_arrow.xml", vector(arrow_body()))
    left, right = arrow_halves()
    # Monochrome (themed icons): tread and arrow only; a separate rim would merge with the tyre at small sizes.
    mono = (p(path(tyre_outline(), list(reversed(circle(TYRE_IN)))), "#FFFFFFFF", even_odd=True)
            + p(path(left), "#FFFFFFFF") + p(path(right), "#FFFFFFFF"))
    write("ic_launcher_monochrome.xml", vector(mono))
    # Status-bar icon: the same silhouette cropped to the badge (white; Android tints it).
    stat = '    <group android:translateX="-20" android:translateY="-20">\n' + mono + '    </group>\n'
    write("ic_stat_ride.xml", vector(stat, size=24, viewport=68))
    if len(sys.argv) > 1:
        preview(sys.argv[1])


def preview(out, px=512):
    """Rough raster of the launcher icon (circle-masked) for eyeballing changes."""
    from PIL import Image, ImageDraw

    k = px / 108.0

    def hexc(h):
        return tuple(int(h[i:i + 2], 16) for i in (3, 5, 7)) + (int(h[1:3], 16),)

    def lin(x1, y1, x2, y2, cols):
        img = Image.new("RGBA", (px, px))
        cs = [hexc(c) for c in cols]
        dx, dy = x2 - x1, y2 - y1
        l2 = dx * dx + dy * dy
        pix = img.load()
        for y in range(px):
            for x in range(px):
                t = max(0.0, min(1.0, ((x / k - x1) * dx + (y / k - y1) * dy) / l2)) * (len(cs) - 1)
                i = min(int(t), len(cs) - 2)
                f = t - i
                pix[x, y] = tuple(int(cs[i][j] + (cs[i + 1][j] - cs[i][j]) * f) for j in range(4))
        return img

    def mask(*loops, even_odd=False):
        m = Image.new("L", (px, px), 0)
        d = ImageDraw.Draw(m)
        for n, loop in enumerate(loops):
            d.polygon([(x * k, y * k) for x, y in loop], fill=0 if (even_odd and n) else 255)
        return m

    img = Image.new("RGBA", (px, px))
    bgimg = Image.new("RGBA", (px, px))
    a, b = hexc(BG_IN), hexc(BG_OUT)
    bp = bgimg.load()
    for y in range(px):
        for x in range(px):
            t = min(1.0, math.hypot(x / k - 54, y / k - 42) / 78)
            bp[x, y] = tuple(int(a[j] + (b[j] - a[j]) * t) for j in range(4))
    img.alpha_composite(bgimg)
    def ring(r, w):
        return mask(circle(r + w / 2), circle(r - w / 2), even_odd=True)

    img.paste(lin(20, 20, 88, 88, BRASS), (0, 0), ring(BEZEL_R, BEZEL_W))
    img.paste(lin(30, 22, 78, 86, RUBBER), (0, 0), mask(tyre_outline(), circle(TYRE_IN), even_odd=True))
    img.paste(Image.new("RGBA", (px, px), (255, 255, 255, 255)), (0, 0),
              ring((TYRE_IN + GROOVE) / 2, 1.0).point(lambda v: v * 0.2))
    img.paste(lin(34, 32, 74, 76, BRASS), (0, 0), ring(RIM_R, RIM_W))
    img.paste(Image.new("RGBA", (px, px), (0, 0, 0, 255)), (0, 0),
              ring(RIM_R - RIM_W / 2 + 0.35, 0.7).point(lambda v: v * 0.4))
    left, right = arrow_halves()
    img.paste(lin(54, 36, 46, 69, EMBER_L), (0, 0), mask(left))
    img.paste(lin(54, 36, 62, 69, EMBER_R), (0, 0), mask(right))
    round_mask = mask(circle(36, 256))
    final = Image.new("RGBA", (px, px), (255, 255, 255, 255))
    final.paste(img, (0, 0), round_mask)
    final.save(out)


if __name__ == "__main__":
    main()
